"""Defensive, in-memory AES-GCM key rotation for Helix Pro blobs.

This changes the encrypted representation while preserving plaintext bytes.
It does not detect attackers, revoke copies already exfiltrated, or erase old
ciphertexts from backups. Callers must manage storage/version replacement.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass

from .cipher import KEY_SIZE, HelixProError, decrypt_bytes, encrypt_bytes


@dataclass(frozen=True)
class RotationResult:
    """New encrypted blob plus integrity metadata for the unchanged plaintext."""

    blob: bytes
    plaintext_sha256: str
    old_blob_sha256: str
    new_blob_sha256: str


def rotate_encrypted_blob(
    blob: bytes,
    old_key: bytes,
    new_key: bytes,
    *,
    aad: bytes = b"",
) -> RotationResult:
    """Authenticate/decrypt with old_key, then encrypt under new_key.

    Plaintext exists only in process memory. The function returns no plaintext.
    A fresh random AES-GCM nonce is generated by encrypt_bytes().
    """
    if len(old_key) != KEY_SIZE or len(new_key) != KEY_SIZE:
        raise HelixProError(f"old_key and new_key must each be {KEY_SIZE} bytes")
    if old_key == new_key:
        raise HelixProError("new_key must differ from old_key")

    plaintext = decrypt_bytes(blob, old_key, aad=aad)
    new_blob = encrypt_bytes(plaintext, new_key, aad=aad)

    # Verify the newly created representation before returning it.
    recovered = decrypt_bytes(new_blob, new_key, aad=aad)
    if recovered != plaintext:
        raise HelixProError("post-rotation verification failed")

    return RotationResult(
        blob=new_blob,
        plaintext_sha256=hashlib.sha256(plaintext).hexdigest(),
        old_blob_sha256=hashlib.sha256(blob).hexdigest(),
        new_blob_sha256=hashlib.sha256(new_blob).hexdigest(),
    )
